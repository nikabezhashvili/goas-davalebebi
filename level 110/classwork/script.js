// თქვენი მიზანია, გამოიყენოთ Set-ი რათა ამ მასივიდან წაშალო დუბლიკატები 
// და შექმნათ მხოლოდ უნიკალური რიცხვებისგან შემდგარი ახალი მასივი. 
arr = [10, 20, 10, 30, 40, 20, 50]
console.log([... new Set(arr)]);

// 2) შექმენით ცარიელი Map-ი, რომელსაც გამოიყენებ სტუდენტების ქულების შესანახად.
// შეასრულეთ შემდეგი ნაბიჯები:

// 2.1) დაამატეთ 3 სტუდენტის სახელი (როგორც Key) და მათი ქულა (როგორც Value). (set)
const newMap = new Map

newMap.set('person1', 75)
newMap.set('person2', 90)
newMap.set('person3', 50)

// 2.2) შეამოწმეთ, არსებობს თუ არა კონკრეტული სტუდენტი (მაგალითად, "გიორგი") ამ Map-ში. (has)
console.log(newMap.has("გიორგი"));

// 2.3) წაშალეთ ერთ-ერთი ნებისმიერი სტუდენტის მონაცემი Map-იდან.
newMap.delete('person3')
console.log(newMap);

// 2.4) წამოიღეთ ერთ-ერთი ნებისმიერი სტუდენტის მონაცემი Map-იდან და დაბეჭდეთ.

const info = newMap.get('person2')
console.log(info);